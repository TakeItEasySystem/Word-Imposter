// Session deck-shuffle engine: guarantees 0 repeats until all sets in the bank are played
export class WordDeck {
  constructor() {
    this.deck = [...WORD_SETS];
    this.shuffle();
    this.currentIndex = 0;
  }

  shuffle() {
    for (let i = this.deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [this.deck[i], this.deck[j]] = [this.deck[j], this.deck[i]];
    }
    this.currentIndex = 0;
  }

  draw(theme = null) {
    if (this.currentIndex >= this.deck.length) {
      this.shuffle();
    }

    if (theme && theme !== "Random Mix" && theme !== "Random Surprise") {
      const matching = this.deck.find(set => 
        set.category.toLowerCase().includes(theme.toLowerCase())
      );
      if (matching) return matching;
    }

    const set = this.deck[this.currentIndex];
    this.currentIndex++;
    return set;
  }
}

export function getRandomWordSet(theme = null) {
  if (theme && theme !== "Random Mix" && theme !== "Random Surprise") {
    const matching = WORD_SETS.filter(set =>
      set.category.toLowerCase().includes(theme.toLowerCase())
    );
    if (matching.length > 0) {
      return matching[Math.floor(Math.random() * matching.length)];
    }
  }
  const index = Math.floor(Math.random() * WORD_SETS.length);
  return WORD_SETS[index];
}
